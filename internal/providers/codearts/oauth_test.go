func mustBegin(t *testing.T, sessions *OAuthSessions, store *config.Store, port int) (OAuthStart, *oauthSession) {
	t.Helper()
	start, err := sessions.Begin(store, port)
	if err != nil {
		t.Fatalf("Begin: %v", err)
	}
	key, err := oauthStoreKey(store)
	if err != nil {
		t.Fatal(err)
	}
	sessions.mu.Lock()
	session := sessions.byStore[key][start.SessionID]
	sessions.mu.Unlock()
	if session == nil {
		t.Fatalf("session %q not found", start.SessionID)
	}
	return start, session
}

func b64url(raw []byte) string {
	return base64.RawURLEncoding.EncodeToString(raw)
}

func decodeB64(t *testing.T, text string) []byte {
	t.Helper()
	raw, err := base64.RawURLEncoding.DecodeString(text)
	if err != nil {
		t.Fatalf("decode base64url %q: %v", text, err)
	}
	return raw
}

func TestOAuthPKCEAndDPoPVectors(t *testing.T) {
	verifier, challenge, err := GeneratePKCE()
	if err != nil {
		t.Fatalf("GeneratePKCE: %v", err)
	}
	if len(verifier) != 86 {
		t.Fatalf("verifier length = %d, want 86 (64 random bytes)", len(verifier))
	}
	if strings.Contains(verifier, "=") || strings.Contains(challenge, "=") {
		t.Fatalf("PKCE values must not be padded: %q %q", verifier, challenge)
	}
	sum := sha256.Sum256([]byte(verifier))
	if challenge != b64url(sum[:]) {
		t.Fatalf("challenge is not S256(verifier)")
	}

	key, err := parseDPoPPrivateKey(json.RawMessage(fixedDPoPJWK))
	if err != nil {
		t.Fatalf("parse fixed JWK: %v", err)
	}
	if key.D.Cmp(big.NewInt(1)) != 0 || key.X.Cmp(key.Curve.Params().Gx) != 0 {
		t.Fatalf("fixed JWK did not parse to d=1/G")
	}

	// Raw JOSE signature interoperability with the Go-generated vector.
	message := []byte("hello-codearts")
	signature, err := hex.DecodeString(goVectorSignature)
	if err != nil {
		t.Fatal(err)
	}
	if !verifyES256(&key.PublicKey, message, signature) {
		t.Fatalf("Go-generated raw r||s vector did not verify")
	}
	if verifyES256(&key.PublicKey, []byte("hello-codeart5"), signature) {
		t.Fatalf("tampered message verified")
	}

	proof, err := DPoPProof(json.RawMessage(fixedDPoPJWK), "POST",
		"https://sts.cn-north-4.myhuaweicloud.com/v1/oauth2/tokens", "nonce-1")
	if err != nil {
		t.Fatalf("DPoPProof: %v", err)
	}
	info, err := VerifyDPoPProof(proof)
	if err != nil {
		t.Fatalf("VerifyDPoPProof: %v", err)
	}
	if info.Htm != "POST" || info.Htu != "https://sts.cn-north-4.myhuaweicloud.com/v1/oauth2/tokens" {
		t.Fatalf("proof claims = %+v", info)
	}
	if info.Nonce != "nonce-1" || info.Iat == 0 || len(info.JTI) != 32 {
		t.Fatalf("proof payload = %+v", info)
	}
	var public map[string]any
	if err := json.Unmarshal(info.PublicJWK, &public); err != nil {
		t.Fatalf("public JWK: %v", err)
	}
	if _, ok := public["d"]; ok {
		t.Fatalf("DPoP header leaked the private scalar: %s", info.PublicJWK)
	}
	if public["kty"] != "EC" || public["crv"] != "P-256" {
		t.Fatalf("public JWK = %s", info.PublicJWK)
	}

	parts := strings.Split(proof, ".")
	if len(parts) != 3 {
		t.Fatalf("proof is not a JWT: %q", proof)
	}
	sig := decodeB64(t, parts[2])
	if len(sig) != 64 {
		t.Fatalf("signature length = %d, want 64", len(sig))
	}
	r := new(big.Int).SetBytes(sig[:32])
	s := new(big.Int).SetBytes(sig[32:])
	n := elliptic.P256().Params().N
	if r.Sign() <= 0 || s.Sign() <= 0 || s.Cmp(new(big.Int).Rsh(n, 1)) > 0 {
		t.Fatalf("signature is not low-S normalized: r=%x s=%x", r, s)
	}

	tampered := parts[0] + "." + parts[1] + "." + b64url(append(append([]byte(nil), sig[:63]...), sig[63]^1))
	if _, err := VerifyDPoPProof(tampered); err == nil {
		t.Fatalf("tampered proof verified")
	}

	generated, err := NewDPoPKey()
	if err != nil {
		t.Fatalf("NewDPoPKey: %v", err)
	}
	generatedKey, err := parseDPoPPrivateKey(generated)
	if err != nil {
		t.Fatalf("generated JWK does not parse: %v", err)
	}
	var fields map[string]string
	if err := json.Unmarshal(generated, &fields); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"kty", "crv", "x", "y", "d"} {
		if fields[name] == "" {
			t.Fatalf("generated JWK missing %q: %s", name, generated)
		}
	}
	if len(decodeB64(t, fields["d"])) != 32 || len(decodeB64(t, fields["x"])) != 32 ||
		len(decodeB64(t, fields["y"])) != 32 {
		t.Fatalf("JWK coordinates must be 32 bytes: %s", generated)
	}
	if generatedKey.Curve != elliptic.P256() {
		t.Fatalf("generated key is not P-256")
	}

	bad := strings.Replace(fixedDPoPJWK,
		"AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAE", "", 1)
	if _, err := DPoPProof(json.RawMessage(bad), "POST", "https://example.test", ""); err == nil {
		t.Fatalf("JWK without d signed a proof")
	}
	// A private scalar that does not match x/y must be rejected.
	mismatch := fmt.Sprintf(`{"kty":"EC","crv":"P-256","x":%q,"y":%q,"d":%q}`,
		public["x"], public["y"], b64url(big.NewInt(2).FillBytes(make([]byte, 32))))
	if _, err := DPoPProof(json.RawMessage(mismatch), "POST", "https://example.test", ""); err == nil {
		t.Fatalf("mismatched JWK signed a proof")
	}
}

func TestOAuthSignRequestMatchesV1Vector(t *testing.T) {
	body := []byte(`{"model":"GLM-5.2","stream":true,"messages":[{"role":"user","content":"hi"}]}`)
	req, err := http.NewRequest("POST",
		"https://snap-access.cn-north-4.myhuaweicloud.com/api/v2/chat/completions", nil)
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Accept", "text/event-stream")
	req.Header.Set("x-auth-token", "TOKEN")
	req.Header.Set("x-snap-traceid", "trace123")
	req.Header.Set("X-Language", "zh-cn")
	req.Header.Set("app-id", "CodeAgent3.0")
	req.Header.Set("is_confidential", "false")

	if err := SignRequestAt(req, body, SignCredentials{
		AccessKeyID: "AKID", SecretAccessKey: "SECRETKEY", SecurityToken: "TOKEN",
	}, "20261031T000000Z"); err != nil {
		t.Fatalf("SignRequestAt: %v", err)
	}
	const expected = "SDK-HMAC-SHA256 Access=AKID, SignedHeaders=accept;app-id;content-type;host;" +
		"is_confidential;x-auth-token;x-language;x-sdk-content-sha256;x-sdk-date;" +
		"x-security-token;x-snap-traceid, Signature=" +
		"28c9c49de88825070ab6fba37f9b30a44bc22f165743bb6c409338cb5b78ad09"
	if got := req.Header.Get("Authorization"); got != expected {
		t.Fatalf("Authorization = %q\nwant %q", got, expected)
	}
	if got := req.Header.Get("Host"); got != "snap-access.cn-north-4.myhuaweicloud.com" {
		t.Fatalf("Host = %q", got)
	}
	if got := req.Header.Get("X-Sdk-Date"); got != "20261031T000000Z" {
		t.Fatalf("X-Sdk-Date = %q", got)
	}
	if got := req.Header.Get("X-Security-Token"); got != "TOKEN" {
		t.Fatalf("X-Security-Token = %q", got)
	}
	if got := req.Header.Get("x-snap-traceid"); got != "trace123" {
		t.Fatalf("caller header mutated: %q", got)
	}
	sum := sha256.Sum256(body)
	if got := req.Header.Get("X-Sdk-Content-Sha256"); got != hex.EncodeToString(sum[:]) {
		t.Fatalf("payload hash = %q", got)
	}

	// Encoded path segments and sorted, percent-encoded query pairs. This
	// vector was produced by v1's sign_request (safe="" quoting).
	req, err = http.NewRequest("GET",
		"https://snap-access.cn-north-4.myhuaweicloud.com/a%20b/c?z=2&a=hello%20world&a=1&blank=", nil)
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("Content-Type", "application/json")
	if err := SignRequestAt(req, nil, SignCredentials{
		AccessKeyID: "AKID", SecretAccessKey: "SECRETKEY", SecurityToken: "TOKEN",
	}, "20261031T000000Z"); err != nil {
		t.Fatalf("SignRequestAt query: %v", err)
	}
	const expectedQuery = "SDK-HMAC-SHA256 Access=AKID, SignedHeaders=content-type;host;" +
		"x-sdk-content-sha256;x-sdk-date;x-security-token, Signature=" +
		"21bdda37c361b802999b593aac7a46f5f3858384305c71af103ad8ce19737c7f"
	if got := req.Header.Get("Authorization"); got != expectedQuery {
		t.Fatalf("query Authorization = %q\nwant %q", got, expectedQuery)
	}

	// Empty security token must not create the header, but is still signed as
	// absent from the canonical headers.
	req, err = http.NewRequest("GET", "https://example.test/path/", nil)
	if err != nil {
		t.Fatal(err)
	}
	if err := SignRequestAt(req, nil, SignCredentials{
		AccessKeyID: "AK", SecretAccessKey: "SK",
	}, "20261031T000000Z"); err != nil {
		t.Fatal(err)
	}
	if req.Header.Get("X-Security-Token") != "" {
		t.Fatalf("empty security token produced a header")
	}
	const expectedDirect = "SDK-HMAC-SHA256 Access=AK, SignedHeaders=host;x-sdk-content-sha256;" +
		"x-sdk-date, Signature=" +
		"012dfca35e242d7466056c6a572c14cde950826f6ef6dfd4fab7bbfcd2788e04"
	if got := req.Header.Get("Authorization"); got != expectedDirect {
		t.Fatalf("direct Authorization = %q\nwant %q", got, expectedDirect)
	}
}

func TestOAuthStartURLStateAndLimits(t *testing.T) {
	store, _ := newOAuthTestStore(t)
	t.Setenv("WB_CODEARTS_PORTAL_HOST", "https://portal.example.test/portal")
	sessions := NewOAuthSessions()
	start, session := mustBegin(t, sessions, store, 8788)

	if !start.OK || start.ExpiresIn != 600 {
		t.Fatalf("OAuthStart = %+v", start)
	}
	sessionID, err := hex.DecodeString(start.SessionID)
	if err != nil || len(sessionID) != 8 {
		t.Fatalf("session id = %q, want 8 hex bytes", start.SessionID)
	}
	ticket, err := hex.DecodeString(session.TicketID)
	if err != nil || len(ticket) != 16 {
		t.Fatalf("ticket id = %q, want 16 hex bytes", session.TicketID)
	}
	secret, err := hex.DecodeString(session.Secret)
	if err != nil || len(secret) != 16 {
		t.Fatalf("secret = %q, want 16 hex bytes", session.Secret)
	}
	if session.State != session.TicketID {
		t.Fatalf("state = %q, want ticket id %q", session.State, session.TicketID)
	}

	const prefix = "https://portal.example.test/portal/authorize?theme=2&locale=zh-cn" +
		"&uri_scheme=codearts-agent&client_id=codearts-agent&port=8788&code_challenge="
	if !strings.HasPrefix(start.AuthURL, prefix) {
		t.Fatalf("authorize URL = %q\nwant prefix %q", start.AuthURL, prefix)
	}
	if !strings.HasSuffix(start.AuthURL, "&code_challenge_method=SHA-256&ticket_id="+
		session.TicketID+"&plugin-name=snap_AIIDE&plugin-version=5.2.0") {
		t.Fatalf("authorize URL tail = %q", start.AuthURL)
	}
	parsed, err := url.Parse(start.AuthURL)
	if err != nil {
		t.Fatal(err)
	}
	query := parsed.Query()
	if query.Get("code_challenge") != challengeForVerifier(session.Verifier) {
		t.Fatalf("code_challenge does not match the session verifier")
	}
	if query.Get("theme") != "2" || query.Get("locale") != "zh-cn" ||
		query.Get("uri_scheme") != "codearts-agent" || query.Get("client_id") != "codearts-agent" ||
		query.Get("port") != "8788" || query.Get("code_challenge_method") != "SHA-256" ||
		query.Get("ticket_id") != session.TicketID || query.Get("plugin-name") != "snap_AIIDE" ||
		query.Get("plugin-version") != "5.2.0" {
		t.Fatalf("authorize query = %v", query)
	}
	for _, forbidden := range []string{"state=", "code=", "code_verifier=", "login_source="} {
		if strings.Contains(start.AuthURL, forbidden) {
			t.Fatalf("authorize URL contains %q: %s", forbidden, start.AuthURL)
		}
	}

	if _, err := sessions.Begin(store, 0); err == nil {
		t.Fatalf("Begin accepted port 0")
	}
	if _, err := sessions.Begin(store, 70000); err == nil {
		t.Fatalf("Begin accepted port 70000")
	}
	if _, err := sessions.Begin(nil, 8788); err == nil {
		t.Fatalf("Begin accepted a nil store")
	}

	// TTL: an expired pending session is removed and cannot be polled.
	session.CreatedAt = sessions.nowTime().Add(-oauthTTL - time.Second)
	if _, err := sessions.Poll(store, start.SessionID); !errors.Is(err, ErrOAuthSession) {
		t.Fatalf("Poll expired session = %v, want ErrOAuthSession", err)
	}
	sessions.mu.Lock()
	if _, exists := sessions.byStore[mustStoreKey(t, store)][start.SessionID]; exists {
		sessions.mu.Unlock()
		t.Fatalf("expired session was not garbage collected")
	}
	sessions.mu.Unlock()

	// Cap: the 65th session evicts the oldest pending session.
	first, firstSession := mustBegin(t, sessions, store, 8788)
	firstSession.CreatedAt = sessions.nowTime().Add(-time.Second)
	for i := 0; i < oauthMaxSessions-1; i++ {
		if _, err := sessions.Begin(store, 8788); err != nil {
			t.Fatalf("Begin %d: %v", i, err)
		}
	}
	sessions.mu.Lock()
	count := len(sessions.byStore[mustStoreKey(t, store)])
	sessions.mu.Unlock()
	if count != oauthMaxSessions {
		t.Fatalf("session count = %d, want %d", count, oauthMaxSessions)
	}
	if _, err := sessions.Begin(store, 8788); err != nil {
		t.Fatalf("Begin at cap: %v", err)
	}
	sessions.mu.Lock()
	_, exists := sessions.byStore[mustStoreKey(t, store)][first.SessionID]
	count = len(sessions.byStore[mustStoreKey(t, store)])
	sessions.mu.Unlock()
	if exists || count != oauthMaxSessions {
		t.Fatalf("oldest session not evicted: exists=%v count=%d", exists, count)
	}

	// Different stores do not share sessions.
	otherStore, _ := newOAuthTestStore(t)
	if _, err := sessions.Poll(otherStore, start.SessionID); !errors.Is(err, ErrOAuthSession) {
		t.Fatalf("foreign store poll = %v, want ErrOAuthSession", err)
	}
}

func challengeForVerifier(verifier string) string {
	sum := sha256.Sum256([]byte(verifier))
	return b64url(sum[:])
}


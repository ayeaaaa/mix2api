// fixedDPoPJWK is the P-256 JWK for d=1 (the standard generator point). ECDSA
// signatures are randomized, so tests verify it rather than compare bytes.
const fixedDPoPJWK = `{"kty":"EC","crv":"P-256","x":"axfR8uEsQkf4vOblY6RA8ncDfYEt6zOg9KE5RdiYwpY","y":"T-NC4v4af5uO5-tKfA-eFivOM1drMV7Oy7ZAaDe_UfU","d":"AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAE"}`

// goVectorSignature is the raw r||s signature generated by the Go
// codearts2api signer for d=1 over "hello-codearts"; Python's verifier pins
// this byte layout.
const goVectorSignature = "8de8b67b0182b0ad3e966bbf0e377da14e3d3850490e4272dfe98933d5a9bf3098e4e89d233a038da948e4cc788be8592cdef4f9aa45229002455be3473322c1"

type oauthFake struct {
	mu sync.Mutex

	tokenCalls  int
	ticketCalls int

	tokenStatus int
	tokenBody   []byte
	tokenFn     func() map[string]any

	ticketStatus int
	ticketBody   []byte
	ticketFn     func() map[string]any

	lastTokenForm   url.Values
	lastTokenHeader http.Header
	lastDPoP        DPoPProofInfo
	lastDPoPErr     error

	lastTicketQuery  url.Values
	lastTicketHeader http.Header

	ticketStarted chan struct{}
	ticketRelease chan struct{}
}

func defaultTokenPayload() map[string]any {
	return map[string]any{
		"user_id":       "u1",
		"user_name":     "账号一",
		"domain_id":     "d1",
		"refresh_token": "refresh-1",
		"credentials": map[string]any{
			"access_key_id":     "AK",
			"secret_access_key": "SK",
			"security_token":    "ST",
			"expiration":        "2030-01-02T03:04:05Z",
		},
	}
}

func (f *oauthFake) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	switch r.URL.Path {
	case "/v1/oauth2/tokens":
		body, _ := io.ReadAll(r.Body)
		form, _ := url.ParseQuery(string(body))
		proof := r.Header.Get("DPoP")
		info, proofErr := VerifyDPoPProof(proof)

		f.mu.Lock()
		f.tokenCalls++
		f.lastTokenForm = form
		f.lastTokenHeader = r.Header.Clone()
		f.lastDPoP = info
		f.lastDPoPErr = proofErr
		status := f.tokenStatus
		raw := append([]byte(nil), f.tokenBody...)
		fn := f.tokenFn
		f.mu.Unlock()

		w.Header().Set("Content-Type", "application/json")
		if status != 0 {
			w.WriteHeader(status)
		}
		if len(raw) > 0 {
			_, _ = w.Write(raw)
			return
		}
		payload := defaultTokenPayload()
		if fn != nil {
			payload = fn()
		}
		_ = json.NewEncoder(w).Encode(payload)

	case "/snap-manager/v1/login/ticket":
		f.mu.Lock()
		f.ticketCalls++
		f.lastTicketQuery = r.URL.Query()
		f.lastTicketHeader = r.Header.Clone()
		status := f.ticketStatus
		raw := append([]byte(nil), f.ticketBody...)
		fn := f.ticketFn
		started := f.ticketStarted
		release := f.ticketRelease
		f.mu.Unlock()

		if started != nil {
			select {
			case started <- struct{}{}:
			default:
			}
		}
		if release != nil {
			<-release
		}

		w.Header().Set("Content-Type", "application/json")
		if status != 0 {
			w.WriteHeader(status)
		}
		if len(raw) > 0 {
			_, _ = w.Write(raw)
			return
		}
		payload := defaultTokenPayload()
		if fn != nil {
			payload = fn()
		}
		_ = json.NewEncoder(w).Encode(payload)

	default:
		http.NotFound(w, r)
	}
}

